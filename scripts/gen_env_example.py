"""Generate .env.example from the bootstrap environment table.

The table is ``code_squad._common.config.bootstrap.BOOTSTRAP_ENV``. Every variable
gets a description comment and its default. Credentials are left empty.

Usage:
  uv run python scripts/gen_env_example.py            # write .env.example
  uv run python scripts/gen_env_example.py --check    # exit 1 if the file has drifted
  uv run python scripts/gen_env_example.py --check --path FILE
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Final

from code_squad._common.config.bootstrap import BOOTSTRAP_ENV, EnvVar

ROOT: Final = Path(__file__).resolve().parent.parent
DEFAULT_TARGET: Final = ROOT / ".env.example"
_SECRET_VARS: Final = frozenset({"LLM_API_KEY", "VCS_TOKEN", "SQUAD_API_TOKEN"})
_HEADER: Final = (
    "# Generated by scripts/gen_env_example.py from the bootstrap table in\n"
    "# code_squad._common.config.bootstrap. Do not edit by hand.\n"
    "# Copy to .env for a local run. Credentials stay empty here: set them in your\n"
    "# shell or a secret file, never commit them.\n"
    "\n"
)


def render() -> str:
    lines = [_HEADER.rstrip("\n"), ""]
    for var in BOOTSTRAP_ENV:
        if var.in_example:
            lines.extend(_entry(var))
    return "\n".join(lines).rstrip("\n") + "\n"


def _entry(var: EnvVar) -> list[str]:
    comment = var.description + (" Required." if var.required else "")
    lines = [f"# {comment}"]
    if var.name in _SECRET_VARS:
        lines.append(
            "# Secret: leave empty here and use the *_FILE variant where one exists."
        )
    lines.append(f"{var.name}={'' if var.name in _SECRET_VARS else var.default or ''}")
    lines.append("")
    return lines


def main(argv: list[str]) -> int:
    target = DEFAULT_TARGET
    if "--path" in argv:
        index = argv.index("--path")
        target = Path(argv[index + 1])
    content = render()
    if "--check" in argv:
        current = target.read_text(encoding="utf-8") if target.exists() else ""
        if current != content:
            print(
                f"{target} is out of date: run scripts/gen_env_example.py",
                file=sys.stderr,
            )
            return 1
        print(f"{target} is up to date")
        return 0
    target.write_text(content, encoding="utf-8")
    print(f"wrote {target}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
